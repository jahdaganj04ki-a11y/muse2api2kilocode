let current: Lang = "de"

export function setLanguage(language: string | undefined) {
  const value = (language ?? "").toLowerCase()
  current = value.startsWith("de") ? "de" : "en"
  // Anything not German falls back to English, matching package.nls.en.json.
  if (!value) current = "de"
}

export function getLanguage(): Lang {
  return current
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const table = current === "de" ? de : en
  let text = table[key] ?? de[key] ?? en[key] ?? key
  for (const [name, value] of Object.entries(vars)) {
    text = text.replace(new RegExp(`\\{${name}\\}`, "g"), String(value))
  }
  return text
}
